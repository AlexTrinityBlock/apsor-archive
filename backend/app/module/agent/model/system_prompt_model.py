"""Owner-authored system prompt sections frozen into each new conversation."""

from datetime import datetime

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    DateTime,
    Identity,
    Index,
    Integer,
    String,
    Text,
    text,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.infrastructure.database.base import Base
from app.shared.time import utcnow


class SystemPromptSectionModel(Base):
    """One prompt section.

    Seeded defaults and owner-authored sections are the same kind of row: all of
    them can be edited, deleted, and reordered. There is no ``builtin_key`` and
    no Python-only fallback list at composition time.

    ``sort_order`` is intentionally not named ``order``: ``ORDER`` is a SQL
    reserved word, and an explicit non-negative integer makes drag-and-drop
    reordering deterministic.
    """

    __tablename__ = "system_prompt_section"
    __table_args__ = (
        # The database constraint and the API schema use the same limits; the
        # migration reuses these names so the schema produced by create_all and by
        # Alembic stays identical.
        CheckConstraint("char_length(title) BETWEEN 1 AND 200", name="title_length"),
        CheckConstraint("char_length(body) BETWEEN 1 AND 32000", name="body_length"),
        CheckConstraint("sort_order >= 0", name="sort_order"),
        # Both listing and conversation setup read by (sort_order, id); the
        # composite index means this ordering needs no extra sort, and it also
        # supports the stable order that breaks ties by id within one sort_order.
        Index("ix_system_prompt_section_order", "sort_order", "id"),
    )

    # ``GENERATED BY DEFAULT AS IDENTITY``: PostgreSQL does not reuse sequence
    # values after the last row is deleted, so an old page or a cached id can never
    # point at a newly created section by mistake.
    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    title: Mapped[str] = mapped_column(String(200), nullable=False)
    body: Mapped[str] = mapped_column(Text, nullable=False)
    sort_order: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
        server_default=text("0"),
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=utcnow,
        server_default=text("now()"),
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=utcnow,
        onupdate=utcnow,
        server_default=text("now()"),
    )


__all__ = ["SystemPromptSectionModel"]
