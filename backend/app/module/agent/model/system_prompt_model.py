"""Owner-authored system prompt sections frozen into each new conversation."""

from datetime import datetime

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    DateTime,
    Identity,
    Index,
    Integer,
    String,
    Text,
    text,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.infrastructure.database.base import Base
from app.shared.time import utcnow


class SystemPromptSectionModel(Base):
    """One ordered prompt section rendered before the built-in prompt.

    ``sort_order`` is intentionally not named ``order``: ``ORDER`` is a SQL
    reserved word, and an explicit non-negative integer makes drag-and-drop
    reordering deterministic. 欄位名使用 ``sort_order`` 而非 SQL 保留字
    ``order``，避免每次查詢都必須加上引號，也讓 ``ORDER BY sort_order, id``
    這個穩定排序在所有 dialect 上都能直接成立。
    """

    __tablename__ = "system_prompt_section"
    __table_args__ = (
        # 資料庫 constraint 與 API schema 採相同上限；migration 直接沿用這些
        # 名稱，確保 create_all 與 Alembic 產生的 schema 完全一致。
        CheckConstraint("char_length(title) BETWEEN 1 AND 200", name="title_length"),
        CheckConstraint("char_length(body) BETWEEN 1 AND 32000", name="body_length"),
        CheckConstraint("sort_order >= 0", name="sort_order"),
        # 列表與對話建立都依 (sort_order, id) 讀取；複合 index 讓這個排序不必
        # 額外 sort，也支援同一 sort_order 時以 id 決勝的穩定順序。
        Index("ix_system_prompt_section_order", "sort_order", "id"),
    )

    # ``GENERATED BY DEFAULT AS IDENTITY``：刪除最後一列後 PostgreSQL 不會
    # 回收序號，舊分頁或快取的 id 因此不會誤指到新建立的 section。
    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    title: Mapped[str] = mapped_column(String(200), nullable=False)
    body: Mapped[str] = mapped_column(Text, nullable=False)
    sort_order: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
        server_default=text("0"),
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=utcnow,
        server_default=text("now()"),
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=utcnow,
        onupdate=utcnow,
        server_default=text("now()"),
    )


__all__ = ["SystemPromptSectionModel"]
