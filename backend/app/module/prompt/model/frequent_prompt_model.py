"""ORM model for the owner-editable frequently used prompts."""

from datetime import datetime

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    DateTime,
    Identity,
    Index,
    Integer,
    String,
    Text,
    text,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.infrastructure.database.base import Base
from app.shared.time import utcnow


class FrequentlyUsedPromptModel(Base):
    """One prompt shortcut shown on the empty chat page.

    The identity column is ``GENERATED BY DEFAULT AS IDENTITY``: deleting the
    last row never lets PostgreSQL hand the same id out again, so a stale
    browser tab cannot edit a newly created prompt by accident.
    """

    __tablename__ = "frequently_used_prompt"
    __table_args__ = (
        CheckConstraint(
            "char_length(title) BETWEEN 1 AND 80",
            name="title_length",
        ),
        CheckConstraint(
            "char_length(prompt_text) BETWEEN 1 AND 4000",
            name="text_length",
        ),
        CheckConstraint("sort_order >= 0", name="sort_order"),
        Index("ix_frequently_used_prompt_order", "sort_order", "id"),
    )

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    title: Mapped[str] = mapped_column(String(80), nullable=False)
    prompt_text: Mapped[str] = mapped_column(Text, nullable=False)
    sort_order: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
        server_default=text("0"),
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=utcnow,
        server_default=text("now()"),
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=utcnow,
        onupdate=utcnow,
        server_default=text("now()"),
    )


__all__ = ["FrequentlyUsedPromptModel"]
