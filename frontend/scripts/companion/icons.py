"""Build the app icons and GitHub artwork from the approved Vellum bust.

Input: ``<work>/icon/bust.png`` (1024×1024 transparent, generated by
``generate.py icon`` and picked by eye).

Usage (from the repository root):

    uv run --no-project --with pillow --with numpy python frontend/scripts/companion/icons.py --work <dir>
"""

from __future__ import annotations

import argparse
import io
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
PUBLIC = REPO / "frontend/public"
ASSETS = REPO / "docs/assets"

PAPER = (240, 233, 216, 255)
INK = (29, 28, 33, 255)
GOLD = (201, 162, 74, 255)
SS = 1024  # supersampled badge size


def bust_on(size: int, bust: Image.Image, fill: float) -> Image.Image:
    """Scale the bust so its width is ``fill`` of ``size`` and bottom-align it."""
    box = bust.getchannel("A").point(lambda v: 255 if v > 30 else 0).getbbox()
    crop = bust.crop(box) if box else bust
    scale = size * fill / crop.width
    crop = crop.resize((round(crop.width * scale), round(crop.height * scale)), Image.Resampling.LANCZOS)
    layer = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    # paste() accepts negative offsets, so a fill above 1.0 crops the shoulders.
    layer.paste(crop, ((size - crop.width) // 2, size - crop.height), crop)
    return layer


def badge(bust: Image.Image, fill: float = 0.98) -> Image.Image:
    """Round paper badge with an ink-and-gold rim, bust clipped to the circle."""
    canvas = Image.new("RGBA", (SS, SS), (0, 0, 0, 0))
    draw = ImageDraw.Draw(canvas)
    draw.ellipse((0, 0, SS - 1, SS - 1), fill=INK)
    rim = int(SS * 0.035)
    draw.ellipse((rim, rim, SS - 1 - rim, SS - 1 - rim), fill=GOLD)
    inner = rim + int(SS * 0.018)
    draw.ellipse((inner, inner, SS - 1 - inner, SS - 1 - inner), fill=PAPER)
    figure = bust_on(SS - 2 * inner, bust, fill)
    clip = Image.new("L", figure.size, 0)
    ImageDraw.Draw(clip).ellipse((0, 0, figure.width - 1, figure.height - 1), fill=255)
    figure.putalpha(Image.composite(figure.getchannel("A"), Image.new("L", figure.size, 0), clip))
    canvas.alpha_composite(figure, (inner, inner))
    return canvas


def small(img: Image.Image, size: int) -> Image.Image:
    out = img.resize((size, size), Image.Resampling.LANCZOS)
    if size <= 64:
        out = out.filter(ImageFilter.UnsharpMask(radius=0.6, percent=60, threshold=1))
    return out


def png_bytes(img: Image.Image, colors: int, dither: Image.Dither) -> bytes:
    quantized = img.quantize(colors=colors, method=Image.Quantize.FASTOCTREE, dither=dither)
    buffer = io.BytesIO()
    quantized.save(buffer, "PNG", optimize=True)
    return buffer.getvalue()


def save_png(img: Image.Image, path: Path, cap: int) -> None:
    # Take the richest palette that fits the cap; otherwise the smallest attempt.
    best = b""
    for dither in (Image.Dither.FLOYDSTEINBERG, Image.Dither.NONE):
        for colors in (256, 192, 128, 96, 64, 48, 32):
            blob = png_bytes(img, colors, dither)
            if not best or len(blob) < len(best):
                best = blob
            if len(blob) <= cap:
                break
        if len(best) <= cap:
            break
    blob = best
    path.write_bytes(blob)
    print(f"{path.relative_to(REPO)}: {len(blob)} bytes")


def font(size: int, bold: bool = True) -> ImageFont.FreeTypeFont | ImageFont.ImageFont:
    serif = "DejaVuSerif-Bold.ttf" if bold else "DejaVuSerif.ttf"
    for name in (f"/usr/share/fonts/truetype/dejavu/{serif}", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"):
        if Path(name).exists():
            return ImageFont.truetype(name, size)
    return ImageFont.load_default()


def social(icon: Image.Image) -> Image.Image:
    width, height = 1280, 640
    card = Image.new("RGBA", (width, height), INK)
    grid = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    grid_draw = ImageDraw.Draw(grid)
    for x in range(0, width, 32):  # faint ledger grid, blended rather than overwritten
        grid_draw.line((x, 0, x, height), fill=(255, 255, 255, 10))
    for y in range(0, height, 32):
        grid_draw.line((0, y, width, y), fill=(255, 255, 255, 10))
    grid_draw.rectangle((34, 34, width - 35, height - 35), outline=(201, 162, 74, 90), width=1)
    card.alpha_composite(grid)
    draw = ImageDraw.Draw(card)
    draw.rectangle((24, 24, width - 25, height - 25), outline=GOLD, width=2)
    mark = icon.resize((440, 440), Image.Resampling.LANCZOS)
    card.alpha_composite(mark, (90, (height - 440) // 2))
    draw.text((590, 210), "Apsor Archive", font=font(84), fill=PAPER)
    draw.line((594, 322, 1150, 322), fill=GOLD, width=2)
    draw.text((594, 344), "A private archive that answers", font=font(34, bold=False), fill=(214, 205, 186, 255))
    draw.text((594, 392), "with its sources.", font=font(34, bold=False), fill=(214, 205, 186, 255))
    return card


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--work", required=True, type=Path)
    args = parser.parse_args()
    bust = Image.open(args.work / "icon/bust.png").convert("RGBA")
    icon = badge(bust)

    # Tab-sized icons zoom onto the head so the silhouette survives 16 px.
    tight = badge(bust, 1.35)
    sizes = [small(tight, 16), small(tight, 32), small(icon, 48)]
    ico = io.BytesIO()
    sizes[-1].save(ico, "ICO", sizes=[(16, 16), (32, 32), (48, 48)], append_images=sizes[:-1])
    (PUBLIC / "favicon.ico").write_bytes(ico.getvalue())
    print(f"frontend/public/favicon.ico: {len(ico.getvalue())} bytes")
    save_png(small(icon, 192), PUBLIC / "icon-192.png", 15 * 1024)
    save_png(small(icon, 512), PUBLIC / "icon-512.png", 40 * 1024)

    touch = Image.new("RGBA", (180, 180), PAPER)
    touch.alpha_composite(bust_on(180, bust, 0.96))
    save_png(touch.convert("RGB").convert("RGBA"), PUBLIC / "apple-touch-icon.png", 15 * 1024)

    ASSETS.mkdir(parents=True, exist_ok=True)
    avatar = Image.new("RGBA", (500, 500), PAPER)
    avatar.alpha_composite(small(icon, 460), (20, 20))
    save_png(avatar, ASSETS / "avatar.png", 60 * 1024)
    save_png(social(icon), ASSETS / "social-preview.png", 300 * 1024)


if __name__ == "__main__":
    main()
