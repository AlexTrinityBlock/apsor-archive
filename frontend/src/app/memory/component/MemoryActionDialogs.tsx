import { useId, useState, type FormEvent } from "react";
import { useQueryClient } from "@tanstack/react-query";

import { Button } from "../../component/Button";
import { Icon } from "../../component/Icon";
import { useToast } from "../../component/Toast";
import {
  useDeprecateMemory,
  useUpdateMemory,
} from "../../generated-apis-types/memories/memories";
import { apiErrorMessage } from "../../settings/component/settings-utils";
import { SettingsDialog } from "../../settings/component/SettingsDialog";
import { invalidateMemorySurfaces } from "../query";

/** The subset of a memory needed by the edit and deprecate dialogs. */
export interface MemoryActionTarget {
  readonly memory_id: number;
  readonly title: string;
  readonly content: string;
  readonly status?: string;
}

interface DialogProps {
  readonly memory: MemoryActionTarget;
  readonly onClose: () => void;
}

/** Edit one memory body; the title is regenerated by the backend. */
export function MemoryEditDialog({ memory, onClose }: DialogProps) {
  const [content, setContent] = useState(memory.content);
  const [error, setError] = useState<string | null>(null);
  const queryClient = useQueryClient();
  const toast = useToast();
  const formId = useId();
  const contentId = useId();

  const mutation = useUpdateMemory({
    mutation: {
      onSuccess: async (updated) => {
        await invalidateMemorySurfaces(queryClient);
        toast.success(`Memory #${updated.memory_id} updated.`);
        onClose();
      },
      onError: (caught) => {
        const message = apiErrorMessage(caught);
        setError(message);
        toast.error(message);
      },
    },
  });

  const submit = (event: FormEvent<HTMLFormElement>) => {
    event.preventDefault();
    const trimmed = content.trim();
    if (trimmed.length === 0) {
      setError("Memory text cannot be empty.");
      return;
    }
    setError(null);
    mutation.mutate({
      memoryId: memory.memory_id,
      data: { content: trimmed },
    });
  };

  return (
    <SettingsDialog
      eyebrow="Memory · edit"
      title="Edit memory text"
      description={`CRYSTAL #${memory.memory_id}. The title is regenerated from the new text; the record keeps its id and occurrence time.`}
      onClose={onClose}
      actions={
        <>
          <Button
            type="button"
            variant="ghost"
            size="sm"
            onClick={onClose}
            disabled={mutation.isPending}
          >
            Cancel
          </Button>
          <Button
            type="submit"
            form={formId}
            variant="primary"
            size="sm"
            disabled={mutation.isPending}
          >
            <Icon name="check" size={14} />
            {mutation.isPending ? "Saving…" : "Save memory"}
          </Button>
        </>
      }
    >
      <form id={formId} className="memory-action-form" onSubmit={submit}>
        <label className="field" htmlFor={contentId}>
          <span className="field-label">Memory text</span>
          <textarea
            id={contentId}
            className="textarea memory-action-form__textarea"
            value={content}
            onChange={(event) => {
              setContent(event.target.value);
              setError(null);
            }}
            maxLength={8000}
            rows={8}
            data-autofocus
            disabled={mutation.isPending}
          />
          <span className="field-help">
            {content.length.toLocaleString()} / 8,000 characters
          </span>
        </label>
        {error ? (
          <p className="memory-action-form__error" role="alert">
            <Icon name="info" size={14} />
            {error}
          </p>
        ) : null}
      </form>
    </SettingsDialog>
  );
}

/** Retire one memory directly; no replacement memory is created. */
export function MemoryDeprecateDialog({ memory, onClose }: DialogProps) {
  const [reason, setReason] = useState("");
  const [error, setError] = useState<string | null>(null);
  const queryClient = useQueryClient();
  const toast = useToast();
  const formId = useId();
  const reasonId = useId();

  const mutation = useDeprecateMemory({
    mutation: {
      onSuccess: async (updated) => {
        await invalidateMemorySurfaces(queryClient);
        toast.success(`Memory #${updated.memory_id} deprecated.`);
        onClose();
      },
      onError: (caught) => {
        const message = apiErrorMessage(caught);
        setError(message);
        toast.error(message);
      },
    },
  });

  const submit = (event: FormEvent<HTMLFormElement>) => {
    event.preventDefault();
    const trimmed = reason.trim();
    setError(null);
    mutation.mutate({
      memoryId: memory.memory_id,
      data: trimmed.length > 0 ? { reason: trimmed } : {},
    });
  };

  return (
    <SettingsDialog
      eyebrow="Memory · deprecate"
      title="Retire this memory?"
      description={`CRYSTAL #${memory.memory_id} keeps its text and stays readable, but leaves default search and the timeline. No replacement memory is written.`}
      onClose={onClose}
      actions={
        <>
          <Button
            type="button"
            variant="ghost"
            size="sm"
            onClick={onClose}
            disabled={mutation.isPending}
          >
            Cancel
          </Button>
          <Button
            type="submit"
            form={formId}
            variant="primary"
            size="sm"
            disabled={mutation.isPending}
          >
            <Icon name="history" size={14} />
            {mutation.isPending ? "Deprecating…" : "Deprecate memory"}
          </Button>
        </>
      }
    >
      <form id={formId} className="memory-action-form" onSubmit={submit}>
        <div className="memory-action-form__target">
          <span className="memory-action-form__id">
            CRYSTAL #{memory.memory_id}
          </span>
          <strong>{memory.title || "Untitled memory"}</strong>
          <p>{memory.content}</p>
        </div>
        <label className="field" htmlFor={reasonId}>
          <span className="field-label">Reason (optional)</span>
          <textarea
            id={reasonId}
            className="textarea memory-action-form__reason"
            value={reason}
            onChange={(event) => {
              setReason(event.target.value);
              setError(null);
            }}
            maxLength={500}
            rows={3}
            placeholder="For example: already bought, cancelled, or no longer true."
            data-autofocus
            disabled={mutation.isPending}
          />
          <span className="field-help">
            Stored on the deprecated record for later provenance.
          </span>
        </label>
        {error ? (
          <p className="memory-action-form__error" role="alert">
            <Icon name="info" size={14} />
            {error}
          </p>
        ) : null}
      </form>
    </SettingsDialog>
  );
}
