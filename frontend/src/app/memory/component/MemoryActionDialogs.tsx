import { useId, useState, type FormEvent } from "react";
import { useQueryClient } from "@tanstack/react-query";

import { Button } from "../../component/Button";
import { Icon } from "../../component/Icon";
import { useToast } from "../../component/Toast";
import {
  useDeprecateMemory,
  useUpdateMemory,
} from "../../generated-apis-types/memories/memories";
import { useApiErrorMessage, useI18n } from "../../i18n";
import { SettingsDialog } from "../../settings/component/SettingsDialog";
import { invalidateMemorySurfaces } from "../query";

/** The subset of a memory needed by the edit and deprecate dialogs. */
export interface MemoryActionTarget {
  readonly memory_id: number;
  readonly title: string;
  readonly content: string;
  readonly status?: string;
}

interface DialogProps {
  readonly memory: MemoryActionTarget;
  readonly onClose: () => void;
}

/** Edit one memory body; the title is regenerated by the backend. */
export function MemoryEditDialog({ memory, onClose }: DialogProps) {
  const { t, formatNumber } = useI18n();
  const apiErrorMessage = useApiErrorMessage();
  const [content, setContent] = useState(memory.content);
  const [error, setError] = useState<string | null>(null);
  const queryClient = useQueryClient();
  const toast = useToast();
  const formId = useId();
  const contentId = useId();

  const mutation = useUpdateMemory({
    mutation: {
      onSuccess: async (updated) => {
        await invalidateMemorySurfaces(queryClient);
        toast.success(t("memory.editDialog.updated", { id: updated.memory_id }));
        onClose();
      },
      onError: (caught) => {
        const message = apiErrorMessage(caught);
        setError(message);
        toast.error(message);
      },
    },
  });

  const submit = (event: FormEvent<HTMLFormElement>) => {
    event.preventDefault();
    const trimmed = content.trim();
    if (trimmed.length === 0) {
      setError(t("memory.editDialog.emptyError"));
      return;
    }
    setError(null);
    mutation.mutate({
      memoryId: memory.memory_id,
      data: { content: trimmed },
    });
  };

  return (
    <SettingsDialog
      eyebrow={t("memory.editDialog.eyebrow")}
      title={t("memory.editDialog.title")}
      description={t("memory.editDialog.description", {
        id: memory.memory_id,
      })}
      onClose={onClose}
      actions={
        <>
          <Button
            type="button"
            variant="ghost"
            size="sm"
            onClick={onClose}
            disabled={mutation.isPending}
          >
            {t("memory.common.cancel")}
          </Button>
          <Button
            type="submit"
            form={formId}
            variant="primary"
            size="sm"
            disabled={mutation.isPending}
          >
            <Icon name="check" size={14} />
            {mutation.isPending
              ? t("memory.editDialog.saving")
              : t("memory.editDialog.save")}
          </Button>
        </>
      }
    >
      <form id={formId} className="memory-action-form" onSubmit={submit}>
        <label className="field" htmlFor={contentId}>
          <span className="field-label">{t("memory.editDialog.label")}</span>
          <textarea
            id={contentId}
            className="textarea memory-action-form__textarea"
            value={content}
            onChange={(event) => {
              setContent(event.target.value);
              setError(null);
            }}
            maxLength={8000}
            rows={8}
            data-autofocus
            disabled={mutation.isPending}
          />
          <span className="field-help">
            {t("memory.editDialog.count", {
              count: formatNumber(content.length),
            })}
          </span>
        </label>
        {error ? (
          <p className="memory-action-form__error" role="alert">
            <Icon name="info" size={14} />
            {error}
          </p>
        ) : null}
      </form>
    </SettingsDialog>
  );
}

/** Retire one memory directly; no replacement memory is created. */
export function MemoryDeprecateDialog({ memory, onClose }: DialogProps) {
  const { t } = useI18n();
  const apiErrorMessage = useApiErrorMessage();
  const [reason, setReason] = useState("");
  const [error, setError] = useState<string | null>(null);
  const queryClient = useQueryClient();
  const toast = useToast();
  const formId = useId();
  const reasonId = useId();

  const mutation = useDeprecateMemory({
    mutation: {
      onSuccess: async (updated) => {
        await invalidateMemorySurfaces(queryClient);
        toast.success(
          t("memory.deprecateDialog.updated", { id: updated.memory_id }),
        );
        onClose();
      },
      onError: (caught) => {
        const message = apiErrorMessage(caught);
        setError(message);
        toast.error(message);
      },
    },
  });

  const submit = (event: FormEvent<HTMLFormElement>) => {
    event.preventDefault();
    const trimmed = reason.trim();
    setError(null);
    mutation.mutate({
      memoryId: memory.memory_id,
      data: trimmed.length > 0 ? { reason: trimmed } : {},
    });
  };

  return (
    <SettingsDialog
      eyebrow={t("memory.deprecateDialog.eyebrow")}
      title={t("memory.deprecateDialog.title")}
      description={t("memory.deprecateDialog.description", {
        id: memory.memory_id,
      })}
      onClose={onClose}
      actions={
        <>
          <Button
            type="button"
            variant="ghost"
            size="sm"
            onClick={onClose}
            disabled={mutation.isPending}
          >
            {t("memory.common.cancel")}
          </Button>
          <Button
            type="submit"
            form={formId}
            variant="primary"
            size="sm"
            disabled={mutation.isPending}
          >
            <Icon name="history" size={14} />
            {mutation.isPending
              ? t("memory.deprecateDialog.saving")
              : t("memory.deprecateDialog.action")}
          </Button>
        </>
      }
    >
      <form id={formId} className="memory-action-form" onSubmit={submit}>
        <div className="memory-action-form__target">
          <span className="memory-action-form__id">
            {t("memory.common.crystal", { id: memory.memory_id })}
          </span>
          <strong>{memory.title || t("memory.common.untitledMemory")}</strong>
          <p>{memory.content}</p>
        </div>
        <label className="field" htmlFor={reasonId}>
          <span className="field-label">
            {t("memory.deprecateDialog.reasonLabel")}
          </span>
          <textarea
            id={reasonId}
            className="textarea memory-action-form__reason"
            value={reason}
            onChange={(event) => {
              setReason(event.target.value);
              setError(null);
            }}
            maxLength={500}
            rows={3}
            placeholder={t("memory.deprecateDialog.reasonPlaceholder")}
            data-autofocus
            disabled={mutation.isPending}
          />
          <span className="field-help">
            {t("memory.deprecateDialog.reasonHelp")}
          </span>
        </label>
        {error ? (
          <p className="memory-action-form__error" role="alert">
            <Icon name="info" size={14} />
            {error}
          </p>
        ) : null}
      </form>
    </SettingsDialog>
  );
}
